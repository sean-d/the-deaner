//! The frame: a tiny outer tmux server (`tmux -L deaner-frame`) whose only job
//! is layout. Its one window holds two panes:
//!
//! ```text
//! ┌ sidebar ─────┬ terminal ───────────────────────────┐
//! │ deaner       │ tmux -L deaner attach (your config, │
//! │ sidebar      │ prefix, status line, tabs)          │
//! └──────────────┴─────────────────────────────────────┘
//! ```
//!
//! The frame has no prefix and no status line; it binds only the focus and
//! sidebar-toggle keys plus mouse handling. One sidebar process serves every
//! workspace, its width is a single pane width, and hiding it is a zoom.

use crate::engine::Engine;
use anyhow::{Context, Result};
use deaner_core::config::FrameKeys;
use deaner_tmux::{Tmux, session_target};
use std::io::Write;
use std::time::Duration;

/// The frame's session name.
pub const FRAME_SESSION: &str = "deaner";
/// Target of the terminal pane.
pub const TERM_PANE: &str = "=deaner:0.1";
/// Target of the sidebar pane.
pub const SIDEBAR_PANE: &str = "=deaner:0.0";
/// Cheat sheet popup size.
const POPUP_WIDTH: &str = "80%";
const POPUP_HEIGHT: &str = "85%";
/// Set in frame panes so subcommands know where they run.
pub const FRAME_ENV: &str = "DEANER_FRAME";

#[must_use]
pub fn frame_socket() -> String {
    std::env::var("DEANER_FRAME_SOCKET").unwrap_or_else(|_| "deaner-frame".into())
}

#[must_use]
pub fn in_frame() -> bool {
    std::env::var_os(FRAME_ENV).is_some()
}

/// The frame server, using deaner's generated config.
#[must_use]
pub fn frame_tmux(engine: &Engine) -> Tmux {
    Tmux::named(frame_socket()).with_config(engine.paths.frame_conf())
}

/// tmux config for the frame server.
#[must_use]
pub fn frame_conf(keys: &FrameKeys, exe: &str) -> String {
    format!(
        r#"# Generated by deaner. Edit [keys] in config.toml instead.
set -g prefix None
set -g prefix2 None
unbind -a -T prefix
unbind -a -T root
set -g base-index 0
set -g pane-base-index 0
set -g status off
set -g mouse on
set -g escape-time 0
set -g focus-events on
set -g history-limit 1
set -g default-terminal "tmux-256color"
set -as terminal-features ",*:RGB"
set -g extended-keys on
set -as terminal-features ",*:extkeys"
set -g allow-passthrough on
set -g set-clipboard on
set -g window-size latest
set -g pane-border-lines single
set -g pane-border-style "fg=brightblack"
set -g pane-active-border-style "fg=brightblack"
set -g popup-style "default"
set -g popup-border-style "fg=brightblack"
set -g popup-border-lines rounded
set -g detach-on-destroy on

bind -n {focus} select-pane -t :.+
bind -n {toggle} select-pane -t :.1 \; resize-pane -Z -t :.1
bind -n {cheatsheet} display-popup -E -w {POPUP_WIDTH} -h {POPUP_HEIGHT} "{exe} cheatsheet"

bind -n MouseDown1Pane select-pane -t = \; send-keys -M
bind -n MouseDrag1Pane send-keys -M
bind -n MouseUp1Pane send-keys -M
bind -n MouseDrag1Border resize-pane -M
bind -n WheelUpPane send-keys -M
bind -n WheelDownPane send-keys -M
bind -n MouseDown3Pane send-keys -M
"#,
        focus = keys.focus,
        toggle = keys.toggle_sidebar,
        cheatsheet = keys.cheatsheet,
    )
}

fn shell_quote(s: &str) -> String {
    shell_words::quote(s).into_owned()
}

/// Run a deaner subcommand in a popup over the frame.
/// Doesn't wait: the popup stays up until the user closes it.
///
/// # Errors
/// When deaner's own path can't be found or tmux can't start.
pub fn open_popup(frame: &Tmux, subcommand: &str) -> Result<()> {
    let exe = std::env::current_exe().context("locating the deaner binary")?;
    let command = format!(
        "env {FRAME_ENV}=1 {} {subcommand}",
        shell_quote(&exe.to_string_lossy())
    );
    let clients = frame.clients();
    let mut args = vec!["display-popup", "-E", "-w", POPUP_WIDTH, "-h", POPUP_HEIGHT];
    if let Some((tty, _)) = clients.first() {
        args.extend(["-c", tty]);
    }
    args.push(&command);
    frame.spawn_detached(&args)?;
    Ok(())
}

/// `deaner` with no arguments: attach to the frame, creating it if needed.
///
/// # Errors
/// When tmux cannot be started.
pub fn open(engine: &Engine) -> Result<()> {
    let exe = std::env::current_exe().context("locating the deaner binary")?;
    let exe = shell_quote(&exe.to_string_lossy());
    crate::paths::write_atomic(
        &engine.paths.frame_conf(),
        &frame_conf(&engine.config.keys, &exe),
    )?;
    let frame = frame_tmux(engine);

    if frame.has_session(FRAME_SESSION) {
        // Pick up key changes from config.toml.
        let _ = frame.run(&[
            "source-file".to_string(),
            engine.paths.frame_conf().to_string_lossy().into_owned(),
        ]);
    } else {
        let (cols, rows) = ratatui::crossterm::terminal::size().unwrap_or((160, 48));
        let state = engine.state();
        let width = state
            .sidebar_width
            .unwrap_or(engine.config.sidebar_width)
            .clamp(16, cols.saturating_sub(20).max(16));
        let env = format!("{FRAME_ENV}=1");
        // Loops keep the panes alive if a process exits or crashes.
        let sidebar = format!("while :; do {exe} sidebar; sleep 1; done");
        let term = format!("while :; do {exe} term; sleep 1; done");
        frame.run(&[
            "new-session",
            "-d",
            "-s",
            FRAME_SESSION,
            "-x",
            &cols.to_string(),
            "-y",
            &rows.to_string(),
            "-e",
            &env,
            &sidebar,
        ])?;
        frame.run(&[
            "split-window",
            "-h",
            "-t",
            SIDEBAR_PANE,
            "-l",
            &cols.saturating_sub(width + 1).to_string(),
            "-e",
            &env,
            &term,
        ])?;
        let focus = if engine.managed_panes().is_empty() {
            SIDEBAR_PANE
        } else {
            TERM_PANE
        };
        let _ = frame.select_pane(focus);
    }
    let status = frame
        .command()
        .args(["attach-session", "-t", &session_target(FRAME_SESSION)])
        .status()
        .context("attaching to the deaner frame")?;
    if !status.success() {
        anyhow::bail!("tmux attach failed");
    }
    Ok(())
}

/// `deaner term`: keep a tmux client for the workspace server attached in the terminal pane.
///
/// # Errors
/// Never in practice; loops until killed.
pub fn term(engine: &Engine) -> Result<()> {
    let frame = frame_tmux(engine);
    let mut placeholder_shown = false;
    loop {
        let sessions: Vec<String> = engine.tmux.sessions();
        if sessions.is_empty() {
            if !placeholder_shown {
                print!("\x1b[2J\x1b[H");
                let key = deaner_ui::keymap::tmux_key_label(&engine.config.keys.focus);
                println!("\n  No workspace open.\n");
                println!("  Pick one in the sidebar ({key} to focus it),");
                println!("  or press `a` there to add a repo.\n");
                println!(
                    "  Workspaces run on their own tmux server:  tmux -L {}",
                    crate::engine::work_socket()
                );
                let _ = std::io::stdout().flush();
                placeholder_shown = true;
            }
            std::thread::sleep(Duration::from_millis(400));
            continue;
        }
        placeholder_shown = false;
        let state = engine.state();
        let target = state
            .last_session
            .filter(|s| sessions.contains(s))
            .unwrap_or_else(|| sessions[0].clone());
        let _ = engine
            .tmux
            .command()
            .args(["attach-session", "-t", &session_target(&target)])
            .status();
        // The client exited. If the session still exists the user detached on
        // purpose: detach the whole frame too. Otherwise the session went away
        // and we reattach to another one.
        if engine.tmux.has_session(&target) {
            let _ = frame.run(&["detach-client", "-s", &session_target(FRAME_SESSION)]);
        }
        std::thread::sleep(Duration::from_millis(150));
    }
}

/// How the sidebar shows a session in the terminal.
pub enum Switcher {
    /// Inside the frame: retarget the terminal pane's tmux client.
    Frame(Tmux),
    /// Running inside a pane of the workspace server: switch that client.
    Inner,
    /// Not inside tmux at all.
    None,
}

impl Switcher {
    #[must_use]
    pub fn detect(engine: &Engine) -> Self {
        if in_frame() {
            return Self::Frame(frame_tmux(engine));
        }
        let inner_socket = std::env::var("TMUX")
            .ok()
            .and_then(|t| t.split(',').next().map(str::to_string))
            .unwrap_or_default();
        if inner_socket.ends_with(&format!("/{}", crate::engine::work_socket())) {
            Self::Inner
        } else {
            Self::None
        }
    }

    /// Show `session` in the terminal. Returns a hint when there is nowhere to show it.
    ///
    /// # Errors
    /// When tmux refuses the switch.
    pub fn show(&self, engine: &Engine, session: &str) -> Result<Option<String>> {
        engine.update_state(|s| s.last_session = Some(session.to_string()))?;
        match self {
            Self::Frame(frame) => {
                if let Some(tty) = frame.display(Some(TERM_PANE), "#{pane_tty}") {
                    // The terminal pane may still be on its placeholder; the term loop
                    // then attaches to `last_session` by itself.
                    if engine.tmux.clients().iter().any(|(t, _)| *t == tty) {
                        engine.tmux.switch_client(Some(&tty), session)?;
                    }
                }
                let _ = frame.select_pane(TERM_PANE);
                Ok(None)
            }
            Self::Inner => {
                engine.tmux.switch_client(None, session)?;
                Ok(None)
            }
            Self::None => Ok(Some(format!(
                "Ready: tmux -L {} attach -t '{session}'",
                crate::engine::work_socket()
            ))),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn conf_binds_configured_keys() {
        let conf = frame_conf(
            &FrameKeys {
                focus: "C-Space".into(),
                toggle_sidebar: "M-b".into(),
                cheatsheet: "F1".into(),
            },
            "/bin/deaner",
        );
        assert!(
            conf.contains(r#"bind -n F1 display-popup -E -w 80% -h 85% "/bin/deaner cheatsheet""#)
        );
        assert!(conf.contains("bind -n C-Space select-pane -t :.+"));
        assert!(conf.contains("bind -n M-b select-pane -t :.1"));
        assert!(conf.contains("set -g prefix None"));
    }
}
